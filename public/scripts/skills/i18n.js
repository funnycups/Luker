/**
 * Register the Skills UI translations. Idempotent — safe to call from
 * every entry point. Returns a Promise that resolves once registration
 * completes; callers can fire-and-forget since the user can't interact
 * with translated strings before the popup mount finishes anyway.
 *
 * Dynamic import of `../i18n.js` keeps the skills modules importable
 * from Jest (where `lib.core.bundle.js` doesn't exist).
 */
export function ensureSkillI18n() {
    if (registered) return Promise.resolve();
    registered = true;
    return import('../i18n.js').then(({ addLocaleData }) => {
        if (typeof addLocaleData !== 'function') return;
        addLocaleData('zh-cn', TRANSLATIONS['zh-cn']);
        addLocaleData('zh-tw', TRANSLATIONS['zh-tw']);
    }).catch(() => {
        // Non-browser environment (e.g. Jest) — skip silently.
    });
}
