/**
 * Locale data + helpers for the memory-graph extension.
 *
 * Lives in its own file to keep main.js focused. This module owns the
 * full zh-CN / zh-TW string tables and the two i18n helper wrappers
 * (`i18n` / `i18nFormat`) used throughout UI rendering.
 *
 * `registerLocaleData` is called once at module bootstrap; everything
 * else can call `i18n` synchronously after that.
 */

const __ctx = Luker.getContext();
const addLocaleData = __ctx.addLocaleData;
const translate = __ctx.translate;

export function i18n(text) {
    return translate(String(text || ''));
}

export function i18nFormat(key, ...values) {
    return i18n(key).replace(/\$\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''));
}

