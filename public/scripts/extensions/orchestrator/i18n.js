/**
 * Unified locale data + helpers for the orchestrator extension.
 *
 * Owns the full zh-CN / zh-TW string tables for runtime runners, UI templates,
 * and the Workbench Orchestra Lens workspace, plus `i18n` / `i18nFormat`.
 */

export function i18n(text) {
    const raw = String(text || '');
    if (!raw) return '';
    const translate = globalThis.Luker?.getContext?.()?.translate;
    return typeof translate === 'function' ? translate(raw) : raw;
}

export function i18nFormat(key, ...values) {
    return i18n(key).replace(/\$\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''));
}

